// Отдельный файл — не украшение: модуль server/llm/client.js целиком
// подменяется в тестах (vi.mock), и новый экспорт из него в таких тестах
// просто исчезал бы. Здесь такой зависимости нет.

/**
 * Обернуть вызов модели меткой фичи.
 *
 * Нужно там, где функция уходит вглубь (пайплайн композиции передаёт её
 * дальше): без обёртки вызовы внутри пайплайна попали бы в учёт как
 * «unknown», и «цена трека» была бы неразделима с «ценой планирования».
 *
 * @param {Function} complete функция вызова модели
 * @param {string} feature метка фичи
 * @returns {Function}
 */
export function withFeature(complete, feature) {
  return (options = {}) => complete({ ...options, feature: options.feature || feature });
}
