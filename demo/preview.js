// Исходник предрассчитанного демо для обложки.
//
// ЗАЧЕМ. Обложка обещает «услышите за 5 секунд». Обещание можно выполнить
// честно только если звук не зависит от LLM, сети и сэмплов: этот трек
// собран из чистых осцилляторов Strudel, поэтому он играет офлайн и мгновенно.
//
// КАК ПЕРЕСОБРАТЬ. npm run build:demo
//   → рендер в WAV (тот же движок, что в студии) → mono/24 кГц → public/demo/preview.wav
//
// ЗВУК. Ми-минор, 2 такта на 120 BPM = ровно 4 секунды. Тихо, без клиппинга:
// громкость выставлена по измерению (см. public/demo/preview.json).

setCpm(120);

// Громкость подобрана по измерению: LUFS-I ≈ −18 LU, true peak ≈ −7 dBTP.
// Это уровень тизера: громко, но без риска клиппинга в наушниках.
$PAD: chord("<c4 eb4 g4 bb4>").s("sawtooth").lpf(900).gain(.22).slow(2);
$BASS: note("<c2 eb2 g2 eb2>").s("sine").gain(1.25).decay(.25);
$PLUCK: note("<g4 bb4 c5 eb5>").s("square").gain(.2).decay(.12).lpf(2200);
$LEAD: note("<c5 eb5 g5 ~>").s("triangle").gain(.72).attack(.01).release(.18);
