// Грув: шаблоны микротайминга на сетке 1/16.
//
// ГРУВ — ЭТО НЕ РАВНОМЕРНЫЙ РАНДОМ. Это структурированные микросдвиги:
// якоря (кик, снейр) стоят плотно на сетке, а перкуссия «гуляет».
//
// Почему шаблоны живут здесь, а не в Strudel:
//   * `swingBy(x, n)` в @strudel/web 1.3.0 ДУБЛИРУЕТ события — 16 хэтов
//     превращаются в 24, даунбеты задваиваются (измерено, см.
//     docs/EVIDENCE-GROOVE.md и tests/spike/swing-semantics.probe.mjs);
//   * `swing(x)` без второго аргумента вообще ничего не меняет;
//   * `.gain("1 .5")` семплится по событию, но `.beat()` с паттерн-аргументом
//     ломает привязку значений.
//
// Поэтому свинг и микротайминг считаются ЗДЕСЬ, в шагах и миллисекундах,
// а компилятор кладёт их в код через сдвиги `.late()` по группам шагов.
// Такой путь детерминирован, прозрачен для аудита и не зависит от
// undocumented-поведения движка.

/** Шаг сетки 1/16 в долях такта. */
export const STEP = 1 / 16;

/** Бюджет микротайминга роли: сдвиг не может превышать 20 мс ни в плюс, ни в минус. */
export const MAX_OFFSET_MS = 20;

import { hash32 } from './prng.js';

/** Длительность 16-й в миллисекундах при заданном темпе. */
export function stepMs(bpm) {
  return 60000 / bpm / 4;
}

/**
 * Длительность такта (одного цикла Strudel) в миллисекундах.
 * Такт = 4 доли = 4 · 60000/BPM мс.
 */
export function barMs(bpm) {
  return 240000 / bpm;
}

