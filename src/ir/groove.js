/**
 * Сдвиг свинга для шага сетки.
 *
 * Свинг делит сетку на пары СВИНУЕМЫХ нот. `unit` — сколько шагов сетки 1/16
 * приходится на одну свингуемую ноту: 1 = свинг 16-х, 2 = свинг 8-х.
 * В паре первая нота тянется, вторая сдвигается на (2s − 1) × длительность
 * свингуемой ноты.
 *
 * Для 8-х (unit = 2) сдвигаются шаги 2, 6, 10, 14 — те самые «и» каждой доли.
 * Для 16-х (unit = 1) — нечётные шаги.
 *
 * ВАЖНО: свингуемая нота стоит на каждом `unit`-м шаге, поэтому вторая нота
 * пары — это шаг с номером `unit` по модулю `2·unit`. Проверка через
 * `floor(step / unit)` сдвигала бы ЛИШНИЕ шаги (при unit = 2 — ещё и 3, 7,
 * 11, 15), а это совсем другой ритм.
 *
 * @param {number} step шаг сетки 1/16
 * @param {number} swing доля 0.5…0.68
 * @param {number} unit шагов сетки на свингуемую ноту (1 = 16-е, 2 = 8-е)
 * @returns {number} сдвиг в тактах
 */
export function swingOffset(step, swing, unit) {
  if (swing <= 0.5) return 0;
  const size = Math.max(1, unit);
  // Вторая нота пары: шаг ≡ size (mod 2·size).
  if (((step % (2 * size)) + 2 * size) % (2 * size) !== size) return 0;
  return (2 * swing - 1) * (size * STEP);
}

/**
 * Собирает сетку роли из шаблона с учётом свинга, силы шаблона и общих
 * настроек IR.
 *
 * @param {object} options
 * @param {string} options.template имя шаблона
 * @param {string} options.role роль ('kick' | 'snare' | 'hats' | 'perc')
 * @param {number} options.bpm темп — нужен для перевода сдвига в миллисекунды
 * @param {number} [options.amount] сила шаблона 0…1
 * @param {number} [options.swing] доля свинга; если не задана — берётся из шаблона
 * @param {number} [options.offsetMs] общий сдвиг роли в миллисекундах
 * @param {number} [options.density] плотность 0…1 (доля оставленных ударов)
 * @param {number} [options.seed] зерно для отсева по плотности
 * @param {string} [options.address] адрес для детерминированного отсева
 * @returns {Array<{step:number, velocity:number, offsetMs:number}>}
 */
export function grooveSteps({
  template,
  role,
  bpm,
  amount = 1,
  swing,
  offsetMs = 0,
  density = 1,
  seed = 0,
  address = '',
}) {
  const spec = GROOVE_TEMPLATES[template] || GROOVE_TEMPLATES.straight;
  const base = spec.steps[role] || [];
  const swingRatio = swing ?? spec.swing;
  // Свинг — свойство хэтов: кик и снейр держат сетку (карка эмоции: «якорь
  // на сетке, перкуссия гуляет»). Свинговые роли: хэты и перкуссия.
  const swingRoles = new Set(['hats', 'perc']);
  const swings = swingRoles.has(role)
    ? base.map(([step]) => swingOffset(step, swingRatio, spec.swingUnit))
    : base.map(() => 0);

  // Порог отсева по плотности. Отсев детерминирован: адресный хэш.
  const out = [];
  base.forEach(([step, velocity, offset], index) => {
    const keep = keepStep({ seed, address, role, step, density, velocity });
    if (!keep) return;
    const swingMs = swings[index] * barMs(bpm);
    // Сила шаблона масштабирует микротайминг: чем меньше amount, тем ровнее.
    const scaled = offset * amount;
    // Бюджет микротайминга: |сдвиг| ≤ 20 мс (guardrail карты groove-templates).
    // Свинг 8-х на медленном темпе даёт до 45 мс — поэтому он упирается в
    // бюджет, а не в неразумную величину. Именно так ограничение и работает:
    // на 80 BPM «свинг» в пределах 20 мс и есть правильный лоуфай-свинг.
    const total = Math.max(-MAX_OFFSET_MS, Math.min(MAX_OFFSET_MS, scaled + swingMs + offsetMs));
    out.push({
      step,
      velocity: round3(velocity),
      offsetMs: round3(total),
    });
  });
  return out;
}

/**
 * Детерминированный отсев шага по плотности.
 *
 * Якоря (динамика ≥ 0.9 — кик на «сильную» долю, основной снейр) НИКОГДА
 * не выбрасываются: иначе трек теряет пульс и становится «жидким».
 * Отсеиваются только тени и призраки.
 *
 * Хэш берётся общий (с финализатором): «голый» FNV давал рваное
 * распределение, и отсев был неравномерным — часть шагов выпадала чаще.
 */
function keepStep({ seed, address, role, step, density, velocity }) {
  if (density >= 1) return true;
  if (velocity >= 0.9) return true;
  if (density <= 0) return false;
  // Хэш решает судьбу шага: адрес (секция, роль) + номер шага.
  const hash = hash32(`${seed}|${address}|${role}|${step}`);
  return hash / 4294967296 < density;
}

function round3(value) {
  return Math.round(value * 1000) / 1000;
}
