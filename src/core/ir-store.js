// Общий доступ к плану трека (Composition IR).
//
// ЗАЧЕМ. План живёт в панели IR (src/ir-panel.js), а помощнику-агенту он
// нужен, чтобы править существующий трек («Дирижёр»). Раньше агент получал
// только код трека, а IR оставался приватной переменной панели — режим
// «Дирижёр» не мог сработать в принципе: инструмент edit_ir требует план,
// а отдать его было нечем.
//
// Правило простое: кто последний собрал или поправил план — тот и есть
// источник истины. Хранилище плоское, без истории: история плана живёт в
// самой панели.

let currentIr = null;

/**
 * Запомнить текущий план трека.
 * @param {object|null} ir
 */
export function setCurrentIr(ir) {
  currentIr = ir ?? null;
}

/**
 * Текущий план трека.
 * @returns {object|null}
 */
export function getCurrentIr() {
  return currentIr;
}
