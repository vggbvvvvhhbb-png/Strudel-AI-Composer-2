// Готовность сэмплов: маленькая чистая функция, чтобы правило проверялось
// тестом, а не глазами.
//
// Правило одно и строгое: трек считается цельным, только если загрузились
// ВСЕ наборы. Половина набора — это неполный трек: без ударных теряется
// ритм, без пианино — мелодия. Сравнивать два неполных трека и учить на
// этом модель бессмысленно, поэтому такая пара помечается «degraded» и в
// обучение не идёт (см. server/taste/dataset.js).
//
// Почему отдельный файл: движок (src/strudel-engine.js) живёт в браузере и
// тестами не покрывается, а решение «считать ли трек цельным» должно быть
// проверено числом, а не догадкой.

/**
 * Все ли наборы сэмплов загрузились.
 *
 * @param {Array<{status?: string}>} results результаты Promise.allSettled
 * @returns {boolean} true — оба набора на месте; false — трек неполный
 */
export function allSamplesReady(results) {
  if (!Array.isArray(results) || results.length === 0) return false;
  return results.every((result) => result?.status === 'fulfilled');
}
