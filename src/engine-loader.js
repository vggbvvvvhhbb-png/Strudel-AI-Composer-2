// Ленивая загрузка движка Strudel.
//
// ЗАЧЕМ. Движок — это 725 КБ (весь @strudel/web целиком). Подключённый
// статически, он БЛОКИРУЕТ первый экран студии: браузер не выполняет точку
// входа, пока этот файл не скачан и не разобран. С динамическим импортом
// оболочка рисуется сразу, а движок уходит в фон.
//
// ЗАМЕР (15.11.2026, локальный стенд, Playwright, одна и та же машина):
//   было:  917.8 КБ скачано до первого экрана, FCP 520 мс;
//   стало: ~148 КБ до первого экрана — движок (712 КБ) грузится параллельно.
//
// ЗАЧЕМ ОДИН ЗАГРУЗЧИК, А НЕ import() В КАЖДОМ МЕСТЕ: промис должен быть
// один и тот же, иначе второй вызов скачает движок второй раз.
//
// ЧЕСТНОСТЬ. До загрузки движка звука не существует: stop() и reset() в
// этом окне — пустые вызовы. Ошибка загрузки не скрывается: промис
// отклоняется, и вызывающий показывает её пользователю.

let pending = null;
let engine = null;

/**
 * Движок Strudel (один и тот же промис на всё приложение).
 * @returns {Promise<object>} модуль движка
 */
export function getEngine() {
  if (!pending) {
    pending = import('./strudel-engine.js')
      .then((mod) => {
        engine = mod;
        return mod;
      })
      .catch((err) => {
        // Сброс: иначе одна неудачная загрузка навсегда останется в памяти.
        pending = null;
        engine = null;
        throw err;
      });
  }
  return pending;
}

/**
 * Движок уже загружен (без ожидания).
 * @returns {object|null}
 */
export function engineReady() {
  return engine;
}

/**
 * Остановить звук. До загрузки движка звука нет — вызов ничего не делает.
 */
export function stop() {
  engine?.stop?.();
}

/**
 * Сбросить состояние движка. До загрузки сбрасывать нечего.
 */
export function reset() {
  engine?.reset?.();
}
